#pragma once

/*  YmckDecode.h - the only place in this program that decides CMYK channel
 *  polarity.
 *
 *  WHY THIS FILE EXISTS
 *  --------------------
 *  A CMYK/YMCK plane looks identical in memory under two opposite conventions:
 *
 *      ink   : 0 = no ink (paper white), 255 = full ink
 *      light : 0 = full ink,             255 = no ink
 *
 *  Reading the source cannot tell them apart - both interpretations stay
 *  self-consistent. That is exactly how three "fixes" in a row (F-M23,
 *  ec8032f, 9746da5) turned real Photoshop files completely black: each one
 *  reasoned from the previous one's assumption instead of from a fact.
 *
 *  Two facts from OUTSIDE this repository fix the polarity:
 *
 *    1. PSD channel planes store the INVERTED value (255 = no ink).
 *       Operational proof: cmyk_chart_rswop.psd (4 channels, RLE, embedded
 *       SWOP profile) renders correctly on build 19897de and renders black
 *       when the plane is not inverted. A sample generated by our own script
 *       cannot prove this - it inherits the same assumption it is meant to
 *       test.
 *
 *    2. lcms2 TYPE_YMCK_8 (see ICCProfileTransform.cpp) must be fed INK
 *       amounts. Same proof: handing it the raw plane made every patch black,
 *       white included.
 *
 *  Therefore: invert the plane exactly once, on the way in, and keep every
 *  YMCK buffer in ink space afterwards. No file outside this header may apply
 *  "255 - channel" to pixel data; .github/scripts/check_ymck_polarity.py
 *  enforces that rule in CI.
 *
 *  The endpoint assertions at the bottom are the guard rail: flipping the
 *  polarity, or applying the naive formula twice, now breaks the build instead
 *  of the release. They are plain arithmetic with no external dependency, so
 *  they also compile and run outside Windows (tests/ymck_decode_test.cpp).
 */

#include <cstddef>
#include <cstdint>
#include <cstring>

namespace YmckDecode {

// Set to 0 only to reproduce the 9746da5 regression; the assertions at the
// bottom of this file then refuse to compile.
#ifndef YMCK_PLANE_IS_INVERTED
#define YMCK_PLANE_IS_INVERTED 1
#endif

constexpr bool kPlaneIsInverted = (YMCK_PLANE_IS_INVERTED != 0);

// A channel byte as the decoder produced it -> an ink amount. Both decoders
// in this program use the same convention (255 = no ink): PSD stores the plane
// inverted, and libjpeg returns Adobe-polarity CMYK/YCCK. Earlier code wrote
// this subtraction out four times; this is now the only place that knows it.
constexpr std::uint8_t ToInk(std::uint8_t plane) noexcept {
    return kPlaneIsInverted ? static_cast<std::uint8_t>(255u - plane) : plane;
}

// 1 - (1 - a) * (1 - b) in 0..255 integer maths. Kept bit-for-bit identical to
// the released implementation: (255 - a) * (255 - b) / 255, no rounding term.
constexpr std::uint8_t Screen(std::uint8_t inkA, std::uint8_t inkB) noexcept {
    return static_cast<std::uint8_t>(
        (static_cast<unsigned>(255u - inkA) * static_cast<unsigned>(255u - inkB)) / 255u);
}

struct Rgb {
    std::uint8_t r, g, b;
};

// Ink amounts to straight RGB.
constexpr Rgb InkToRgb(std::uint8_t c, std::uint8_t m, std::uint8_t y, std::uint8_t k) noexcept {
    return Rgb{ Screen(c, k), Screen(m, k), Screen(y, k) };
}

// The YMCK layout both decoders produce in memory: p[0]=Y, p[1]=M, p[2]=C,
// p[3]=K. Keeping the permutation here means call sites cannot get it wrong.
constexpr Rgb YmckToRgb(std::uint8_t y, std::uint8_t m, std::uint8_t c, std::uint8_t k) noexcept {
    return InkToRgb(c, m, y, k);
}

// The one and only plane inversion. strideBytes == 5 covers the dormant
// "CMYK + alpha" layout that PSDWrapper still carries; the live path is 4.
// In that 5-byte layout the leading alpha byte is skipped and the four colour
// bytes after it are inverted, which is what the replaced loop did.
// memcpy keeps it alignment-safe (the replaced code cast the buffer directly).
inline void InvertPlaneInPlace(void* pixels, std::size_t count, std::size_t strideBytes = 4) noexcept {
    auto* p = static_cast<std::uint8_t*>(pixels) + (strideBytes - 4); // 0 for 4, 1 for 5
    for (std::size_t i = 0; i < count; ++i, p += strideBytes) {
        std::uint32_t word;
        std::memcpy(&word, p, sizeof word);
        word = ~word;
        std::memcpy(p, &word, sizeof word);
    }
}

// ---------------------------------------------------------------------------
// Endpoint assertions (A1-A4). These encode what the *picture* must look like,
// not what the code happens to compute, so a polarity flip cannot "pass".
// ---------------------------------------------------------------------------

// A1: a file byte of 255 is no ink, so an all-255 plane must stay pure white.
constexpr Rgb kA1 = YmckToRgb(ToInk(255), ToInk(255), ToInk(255), ToInk(255));
static_assert(kA1.r == 255 && kA1.g == 255 && kA1.b == 255,
              "A1: a plane byte of 255 must be no ink, i.e. white (polarity flipped?)");

// A2: a file byte of 0 is full ink, so an all-0 plane must be black.
constexpr Rgb kA2 = YmckToRgb(ToInk(0), ToInk(0), ToInk(0), ToInk(0));
static_assert(kA2.r == 0 && kA2.g == 0 && kA2.b == 0,
              "A2: a plane byte of 0 must be full ink, i.e. black (polarity flipped?)");

// A3: a K-only ramp must be neutral and strictly darker with every step.
constexpr bool KOnlyRampIsNeutralAndDarker() noexcept {
    int previous = 256;
    for (int k = 0; k <= 255; ++k) {
        const Rgb rgb = InkToRgb(0, 0, 0, static_cast<std::uint8_t>(k));
        if (rgb.r != rgb.g || rgb.g != rgb.b) return false;
        if (rgb.r >= previous) return false;
        previous = rgb.r;
    }
    return true;
}
static_assert(KOnlyRampIsNeutralAndDarker(),
              "A3: a K-only ramp must be grey and monotonically darker (double inversion?)");

// A4: the three primaries pin the channel order. Y/M/C swapped anywhere shows
// up here as the wrong corner of the cube.
constexpr Rgb kCyan = YmckToRgb(ToInk(255), ToInk(255), ToInk(0), ToInk(255));
constexpr Rgb kMagenta = YmckToRgb(ToInk(255), ToInk(0), ToInk(255), ToInk(255));
constexpr Rgb kYellow = YmckToRgb(ToInk(0), ToInk(255), ToInk(255), ToInk(255));
static_assert(kCyan.r == 0 && kCyan.g == 255 && kCyan.b == 255,
              "A4: full cyan must be (0,255,255) - channel order or polarity is wrong");
static_assert(kMagenta.r == 255 && kMagenta.g == 0 && kMagenta.b == 255,
              "A4: full magenta must be (255,0,255) - channel order or polarity is wrong");
static_assert(kYellow.r == 255 && kYellow.g == 255 && kYellow.b == 0,
              "A4: full yellow must be (255,255,0) - channel order or polarity is wrong");

} // namespace YmckDecode
